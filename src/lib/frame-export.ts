import { PenNode } from '../types/pen-ast';
import { renderNodeHtml } from '../compiler/ast-to-html';

/** Sharper than the design's CSS size, so exports hold up on retina screens and in print */
const DEFAULT_PIXEL_RATIO = 2;
/** Largest canvas side every major browser accepts */
const MAX_CANVAS_SIDE = 16_384;
/** Safari's canvas area cap, the lowest of the major browsers */
const MAX_CANVAS_PIXELS = 16_777_216;
/** Drawn in place of images the browser may not read (cross-origin without CORS): a dark 1x1 PNG */
const BLOCKED_IMAGE_PLACEHOLDER =
  'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNkqAcAAIUAgUW0RjgAAAAASUVORK5CYII=';

export interface RasterSize {
  width: number;
  height: number;
}

/** Design size of an export root, rejecting empty ones */
export function exportSize(root: PenNode): RasterSize {
  const width = Math.round(root.width ?? 0);
  const height = Math.round(root.height ?? 0);
  if (width < 1 || height < 1) throw new Error('Phần tử được chọn không có kích thước để xuất.');
  return { width, height };
}

/** Pixel ratio for `size`, lowered when the default would exceed browser canvas limits */
export function exportPixelRatio(size: RasterSize, preferred: number = DEFAULT_PIXEL_RATIO): number {
  const bySide = MAX_CANVAS_SIDE / Math.max(size.width, size.height);
  const byArea = Math.sqrt(MAX_CANVAS_PIXELS / (size.width * size.height));
  return Math.min(preferred, bySide, byArea);
}

/**
 * Renders `root` with the same markup as the HTML export into an off-screen
 * host, so the PNG matches the exported page rather than the editor chrome.
 * The markup is generated by renderNodeHtml, which escapes text and
 * whitelists CSS values and image sources.
 */
function mountOffscreen(root: PenNode, size: RasterSize): { node: HTMLElement; dispose: () => void } {
  const host = document.createElement('div');
  host.setAttribute('aria-hidden', 'true');
  Object.assign(host.style, {
    position: 'fixed',
    left: `${-(size.width + 100)}px`,
    top: '0px',
    pointerEvents: 'none',
    fontFamily: 'Inter, system-ui, -apple-system, sans-serif',
  });
  host.innerHTML = renderNodeHtml(root, true);
  document.body.appendChild(host);
  const node = host.firstElementChild as HTMLElement | null;
  if (!node) {
    host.remove();
    throw new Error('Không dựng được nội dung để xuất.');
  }
  return { node, dispose: () => host.remove() };
}

/** Rasterises `root` to a PNG data URL */
export async function renderPng(root: PenNode): Promise<{ dataUrl: string; size: RasterSize }> {
  const size = exportSize(root);
  const { toPng } = await import('html-to-image');
  const { node, dispose } = mountOffscreen(root, size);
  try {
    const dataUrl = await toPng(node, {
      width: size.width,
      height: size.height,
      pixelRatio: exportPixelRatio(size),
      cacheBust: true,
      imagePlaceholder: BLOCKED_IMAGE_PLACEHOLDER,
    });
    return { dataUrl, size };
  } finally {
    dispose();
  }
}

/** One-page PDF the size of `root`, with the design as a PNG */
export async function renderPdf(root: PenNode): Promise<Blob> {
  const { dataUrl, size } = await renderPng(root);
  const { jsPDF } = await import('jspdf');
  const pdf = new jsPDF({
    orientation: size.width > size.height ? 'landscape' : 'portrait',
    unit: 'px',
    format: [size.width, size.height],
    hotfixes: ['px_scaling'],
    compress: true,
  });
  pdf.addImage(dataUrl, 'PNG', 0, 0, size.width, size.height);
  return pdf.output('blob');
}

/** Turns a data URL into a Blob without a network round-trip */
export function dataUrlToBlob(dataUrl: string): Blob {
  const [header, base64] = dataUrl.split(',', 2);
  const mimeType = /^data:([^;]+);base64$/.exec(header)?.[1] ?? 'application/octet-stream';
  const binary = atob(base64 ?? '');
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i += 1) bytes[i] = binary.charCodeAt(i);
  return new Blob([bytes], { type: mimeType });
}
